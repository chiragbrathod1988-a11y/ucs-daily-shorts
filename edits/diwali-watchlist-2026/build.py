"""Build audio + src/diwaliData.ts for the Diwali Breakout Watchlist reel.
Usage: python3 edits/diwali-watchlist-2026/build.py   (needs tts/diwali-watchlist-2026/*.mp3)
"""
import json, os, subprocess, shutil

NAME = "diwali-watchlist-2026"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
TTS = os.path.join(ROOT, "tts", NAME)
PUB = os.path.join(ROOT, "public", "diwali")
os.makedirs(PUB, exist_ok=True)

# On-screen captions (romanised), one per voice line
CAP = {
    "hook": "Diwali pe 2 bade Bank stocks ne consolidation tod diya!",
    "hook2": "Diwali Breakout Watchlist — end tak dekhna",
    "i1": "ICICI Bank: range 1,195 – 1,505",
    "i2": "Monthly candle 1,505 ke upar — 1,576 (+12.7%)",
    "i3": "Projection zone 2,358 — chart study, guarantee nahi",
    "if1": "Q2 Net Profit ₹14,843 Cr (+20%)",
    "if2": "NIM 4.18% • Net NPA sirf 0.30%",
    "if3": "MF holding ~29% • FII ne stake badhaya",
    "k1": "Kotak Bank: range 317 – 450",
    "k2": "Breakout 450 ke upar — ab 480 • zone 699",
    "kf1": "Q2 Net Profit ₹4,212 Cr (+29%)",
    "kf2": "NIM 4.31% • Net NPA 0.24% • CAR ~22%",
    "kf3": "DII 38.5% (badha) • Promoter ~26%",
    "risk": "Breakout tabhi strong jab price level ke upar tike",
    "cta": "Breakout stocks khud dhoondo — AI Dashboard",
    "cta2": "Happy Diwali! Save • Share • Follow",
}
GAP = {"hook2": 0.5, "i3": 0.35, "if3": 0.45, "k2": 0.35, "kf3": 0.45, "risk": 0.4, "cta": 0.25}

man = json.load(open(os.path.join(TTS, "manifest.json")))
dur = lambda p: float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", p],
                                     check=True, capture_output=True, text=True).stdout)
t = 0.5
timeline, parts = [], []
TEMPO = 1.12
FAST = os.path.join(PUB, "fast"); os.makedirs(FAST, exist_ok=True)
for ln in man["lines"]:
    tag = ln["tag"]; p = os.path.join(FAST, tag + ".wav")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", os.path.join(TTS, tag + ".mp3"), "-af", f"atempo={TEMPO}", "-ar", "48000", p], check=True)
    d = dur(p)
    timeline.append({"tag": tag, "start": round(t, 3), "end": round(t + d, 3), "cap": CAP[tag]})
    parts.append((p, t))
    t += d + GAP.get(tag, 0.22)
total = round(t + 2.2, 3)

# voice track: place each clip at its start time
inputs, filt = [], []
for i, (p, st) in enumerate(parts):
    inputs += ["-i", p]
    filt.append(f"[{i}:a]aresample=48000,aformat=channel_layouts=stereo,adelay={int(st*1000)}|{int(st*1000)}[a{i}]")
filt.append("".join(f"[a{i}]" for i in range(len(parts))) + f"amix=inputs={len(parts)}:normalize=0,apad,atrim=0:{total}[v]")
voice = os.path.join(PUB, "voice.wav")
subprocess.run(["ffmpeg", "-v", "error", "-y", *inputs, "-filter_complex", ";".join(filt), "-map", "[v]", voice], check=True)

music = os.path.join(PUB, "music.wav")
subprocess.run(["python3", os.path.join(ROOT, "scripts", "music.py"), music, str(total)], check=True, cwd=ROOT)
mix = os.path.join(PUB, "mix.wav")
subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", voice, "-i", music, "-filter_complex",
                f"[1:a]volume=0.16,afade=t=out:st={total-2}:d=2[m];[0:a]volume=1.0[vv];[vv][m]amix=inputs=2:normalize=0,"
                "alimiter=limit=0.95[o]", "-map", "[o]", "-ar", "48000", mix], check=True)

for src, dst in [("6159d212-image.png", "icici.png"), ("ee26fd75-image.png", "kotak.png")]:
    s = os.path.join(HERE, dst)
    shutil.copy(s, os.path.join(PUB, dst))
for f in ["logo.png", "chirag.png"]:
    shutil.copy(os.path.join(ROOT, "public", "daily", f), os.path.join(PUB, f))

open(os.path.join(ROOT, "src", "diwaliData.ts"), "w").write(
    "// generated by edits/diwali-watchlist-2026/build.py\nexport const DIWALI = " +
    json.dumps({"total": total, "timeline": timeline}, ensure_ascii=False, indent=1) + " as const;\n")
print(json.dumps({"total": total, "timeline": [(x["tag"], x["start"]) for x in timeline]}))
